package day1;

public class LoopDemo {

	public static void main(String[] args) {
		
		//initialisation			where the loop starts from 1							3 seperate lines				all in a single line
																							//(while)						for
		//condition					till where the loop should run  <=5
		
		//increment/dec				move the loop forwards
		
		
		int i;
		
		i=1;			//initialisation
		
		while(i<=5)		//condition
		{
			System.out.println("Alice");
			i+=1;		//increment
		}
		
		
		for(i=1;i<=5;i+=1)		
			System.out.println("Alice");
	}

}

